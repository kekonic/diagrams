#!/usr/bin/env node
/**
 * Generate theme.css for @kekonic/diagrams-theme and @kekonic/diagrams.
 * Requires a prior `vp pack` so dist/index.mjs exists.
 *
 *   pnpm --filter @kekonic/diagrams-theme generate:theme-css
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getThemeTokens, THEME_CSS } from "../dist/index.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const themePkg = join(here, "..");
const metaPkg = join(themePkg, "../diagrams");

function block(mode, selector) {
  const tokens = getThemeTokens(mode);
  const lines = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

const css = `/* Generated by scripts/generate-theme-css.mjs — do not edit by hand. */

${block("dark", '.k-diagram, .k-diagram[data-theme="dark"], .k-diagram.kdiagram-theme-dark, :root, :root[data-theme="dark"]')}

${block("light", '.k-diagram[data-theme="light"], .k-diagram.kdiagram-theme-light, :root[data-theme="light"]')}
${THEME_CSS}
`;

writeFileSync(join(themePkg, "theme.css"), css);
writeFileSync(join(metaPkg, "theme.css"), css);
console.log(`wrote theme.css (${css.length} bytes) → diagrams-theme + diagrams`);
